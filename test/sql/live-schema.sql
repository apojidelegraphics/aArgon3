-- A stand-in for the live aARgon3 & Mexel Backend (as of 2026-11-19): Supabase's roles and the four existing tables,
-- with RLS off, like production. test/sql.test.js loads this into a scratch Postgres, then runs aargon3-2.0.sql twice.
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
end $$;
grant usage on schema public to anon, authenticated, service_role;
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant execute on functions to anon, authenticated, service_role;

create table public.promotions (id bigserial primary key, code text unique not null, discount_type text not null check (discount_type in ('percentage','fixed')),
  discount_value numeric not null, min_order_total numeric default 0, max_discount numeric, start_date timestamptz not null, end_date timestamptz not null,
  is_active boolean default true, usage_limit int, used_count int default 0, applicable_plans text[], applicable_tiers text[], created_at timestamptz default now());
create table public.orders (id bigint generated by default as identity primary key, created_at timestamptz not null default now(), order_id text,
  store_name text, operator text, plan_type text, customer_name text, total_price text, items jsonb, notes text, config json, payment_method text,
  status text default 'ACTIVE', repinged_at timestamptz, currency text default 'USD', exchange_rate numeric default 1.0, shift_id bigint,
  promo_code text, discount_amount numeric default 0, node_id text, target_jurisdiction text, customer_email text);
create table public.shifts (id bigserial primary key, employee_name text not null, store_name text not null, clock_in timestamptz not null default now(),
  clock_out timestamptz, status text default 'active', total_sales numeric default 0, total_orders int default 0, created_at timestamptz default now());
create table public.terms (id bigint generated by default as identity primary key, content text);

grant all on all tables in schema public to anon, authenticated, service_role;
grant all on all sequences in schema public to anon, authenticated, service_role;

