// npm run catalog — copies catalog.json + scripts/core.js into the two places that use them:
//   assets/catalog.js                          the store and the staff terminal (window.A3)
//   supabase/functions/_shared/catalog.mjs      the Supabase Edge Functions (import { A3 } from '../_shared/catalog.js')
// npm test fails if either copy is out of date, so prices can't drift between the site and the server.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

function build() {
  const C = JSON.parse(fs.readFileSync(path.join(ROOT, 'catalog.json'), 'utf8'));
  delete C._note;
  const { core } = require('./core');
  const head = '/* Generated by scripts/catalog.js from catalog.json and scripts/core.js. Edit those, then run `npm run catalog`. */\n';
  const body = `const CATALOG = ${JSON.stringify(C, null, 2)};\n${core.toString()}\n`;
  return {
    web: `${head}(function () {\n${body}window.A3 = core(CATALOG);\n})();\n`,
    server: `${head}${body}export const A3 = core(CATALOG);\n`
  };
}
const OUT = { web: path.join(ROOT, 'assets', 'catalog.js'), server: path.join(ROOT, 'supabase', 'functions', '_shared', 'catalog.mjs') };

if (require.main === module) {
  const b = build();
  for (const k of Object.keys(OUT)) { fs.mkdirSync(path.dirname(OUT[k]), { recursive: true }); fs.writeFileSync(OUT[k], b[k]); }
  console.log('catalog: wrote assets/catalog.js and supabase/functions/_shared/catalog.mjs');
}
module.exports = { build, OUT };
