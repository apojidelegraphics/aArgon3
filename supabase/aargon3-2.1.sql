$$;

-- ============================================================ staff & roles
-- Called on every sign-in. Returns the staff row, or null if this person may not use aARgon3.
-- p_level: their Nexus admin level (null if not a Nexus admin). p_owner: their email is the owner's.
create or replace function public.a3_staff_sync(p_user uuid, p_email text, p_name text, p_level text, p_owner boolean) returns jsonb
language plpgsql security definer set search_path = public as $$
declare s public.staff; e text := lower(trim(p_email));
begin
  select * into s from staff where user_id = p_user or email = e order by (user_id = p_user) desc nulls last limit 1;
  if s.id is null then
    if p_level is null and not p_owner then return null; end if;
    insert into staff (user_id, email, name, role, invited_by)
    values (p_user, e, p_name, case when p_owner then 'owner' when p_level = 'high-admin' then 'manager' else 'employee' end, 'Nexus admin')
    returning * into s;
  else
    update staff set user_id = p_user, email = e, name = coalesce(nullif(p_name, ''), name), last_seen = now(),
                     role = case when p_owner then 'owner' when role = 'owner' then 'manager' else role end,
                     active = case when p_owner then true else active end
     where id = s.id returning * into s;
  end if;
  return public.a3_staff_json(s, true);
end $$;

create or replace function public.a3_staff_list(p_with_pay boolean, p_tz text default 'America/New_York') returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.a3_staff_json(s, p_with_pay) || jsonb_build_object(
      'on_clock', (select public.a3_shift_json(x) from shifts x where x.user_id = s.user_id and x.clock_out is null),
      'week_minutes', (select coalesce(sum(public.a3_minutes(x)), 0) from shifts x where x.user_id = s.user_id
                         and x.clock_in >= (date_trunc('week', now() at time zone p_tz) at time zone p_tz)),
      'month_sales', (select coalesce(sum(public.a3_amount(o)), 0) from orders o where o.staff_user_id = s.user_id and public.a3_counts(o)
                         and o.created_at >= (date_trunc('month', now() at time zone p_tz) at time zone p_tz)),
      'next_shift', (select jsonb_build_object('starts_at', c.starts_at, 'ends_at', c.ends_at, 'store_code', c.store_code)
                       from schedule c where c.user_id = s.user_id and c.ends_at > now() order by c.starts_at limit 1))
    order by case s.role when 'owner' then 0 when 'manager' then 1 else 2 end, not s.active, coalesce(nullif(s.display_name, ''), s.name, s.email)), '[]'::jsonb)
  from staff s
$$;

-- add or edit someone (the staff function decides who may change what)
create or replace function public.a3_staff_save(p jsonb, p_by text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare s public.staff; e text := lower(trim(p->>'email'));
begin
  if (p->>'id') is not null then
    update staff set
      display_name = case when p ? 'display_name' then nullif(trim(p->>'display_name'), '') else display_name end,
      role = case when p ? 'role' then p->>'role' else role end,
      active = case when p ? 'active' then (p->>'active')::boolean else active end,
      title = case when p ? 'title' then nullif(trim(p->>'title'), '') else title end,
      phone = case when p ? 'phone' then nullif(trim(p->>'phone'), '') else phone end,
      default_store = case when p ? 'default_store' then nullif(p->>'default_store', '') else default_store end,
      color = case when p ? 'color' then nullif(p->>'color', '') else color end,
      notes = case when p ? 'notes' then nullif(trim(p->>'notes'), '') else notes end,
      pay_rate = case when p ? 'pay_rate' then nullif(p->>'pay_rate', '')::numeric else pay_rate end,
      updated_at = now()
    where id = (p->>'id')::bigint returning * into s;
    if s.id is null then raise exception 'That person isn''t on the staff list.'; end if;
  else
    if e is null or e !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then raise exception 'Enter their email (the one they use for Nexus).'; end if;
    if exists (select 1 from staff where email = e) then raise exception 'They''re already on the staff list.'; end if;
    insert into staff (email, display_name, role, title, phone, default_store, pay_rate, notes, invited_by)
    values (e, nullif(trim(p->>'display_name'), ''), coalesce(p->>'role', 'employee'), nullif(trim(p->>'title'), ''), nullif(trim(p->>'phone'), ''),
            nullif(p->>'default_store', ''), nullif(p->>'pay_rate', '')::numeric, nullif(trim(p->>'notes'), ''), p_by)
    returning * into s;
  end if;
  return public.a3_staff_json(s, true);
end $$;

create or replace function public.a3_staff_get(p_id bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select public.a3_staff_json(s, true) from staff s where s.id = p_id
$$;

-- ============================================================ schedule & time off
create or replace function public.a3_schedule(p_from timestamptz, p_to timestamptz, p_user uuid default null) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'user_id', c.user_id, 'store_code', c.store_code, 'starts_at', c.starts_at, 'ends_at', c.ends_at,
      'note', c.note, 'created_by', c.created_by,
      'name', (select coalesce(nullif(s.display_name, ''), s.name, split_part(s.email, '@', 1)) from staff s where s.user_id = c.user_id),
      'color', (select s.color from staff s where s.user_id = c.user_id),
      'time_off', exists (select 1 from time_off t where t.user_id = c.user_id and t.status = 'approved'
                            and (c.starts_at at time zone 'America/New_York')::date between t.starts_on and t.ends_on),
      'worked', (select public.a3_minutes(x) from shifts x where x.scheduled_id = c.id limit 1))
    order by c.starts_at), '[]'::jsonb)
  from schedule c where c.starts_at < p_to and c.ends_at > p_from and (p_user is null or c.user_id = p_user)
$$;

create or replace function public.a3_schedule_save(p jsonb, p_by text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare c public.schedule; u uuid := (p->>'user_id')::uuid;
begin
  if not exists (select 1 from staff where user_id = u and active) then raise exception 'Pick someone who has signed in to aARgon3 at least once.'; end if;
  if (p->>'ends_at')::timestamptz <= (p->>'starts_at')::timestamptz then raise exception 'The shift has to end after it starts.'; end if;
  if (p->>'ends_at')::timestamptz - (p->>'starts_at')::timestamptz > interval '16 hours' then raise exception 'A shift can be 16 hours at most.'; end if;
  if exists (select 1 from schedule x where x.user_id = u and x.id is distinct from (p->>'id')::bigint
               and x.starts_at < (p->>'ends_at')::timestamptz and x.ends_at > (p->>'starts_at')::timestamptz) then
    raise exception 'That overlaps another shift for the same person.'; end if;
  if (p->>'id') is not null then
    update schedule set user_id = u, store_code = nullif(p->>'store_code', ''), starts_at = (p->>'starts_at')::timestamptz, ends_at = (p->>'ends_at')::timestamptz,
                        note = nullif(trim(p->>'note'), '') where id = (p->>'id')::bigint returning * into c;
    if c.id is null then raise exception 'That shift doesn''t exist.'; end if;
  else
    insert into schedule (user_id, store_code, starts_at, ends_at, note, created_by)
    values (u, nullif(p->>'store_code', ''), (p->>'starts_at')::timestamptz, (p->>'ends_at')::timestamptz, nullif(trim(p->>'note'), ''), p_by)
    returning * into c;
  end if;
  return to_jsonb(c);
end $$;

create or replace function public.a3_schedule_delete(p_id bigint) returns integer
language plpgsql security definer set search_path = public as $$
declare n int; begin delete from schedule where id = p_id; get diagnostics n = row_count; return n; end $$;

-- copies one week's shifts onto the next week (skips any that would overlap)
create or replace function public.a3_schedule_copy_week(p_from timestamptz, p_by text) returns integer
language plpgsql security definer set search_path = public as $$
declare n int := 0; c record;
begin
  for c in select * from schedule where starts_at >= p_from and starts_at < p_from + interval '7 days' loop
    if not exists (select 1 from schedule x where x.user_id = c.user_id and x.starts_at < c.ends_at + interval '7 days' and x.ends_at > c.starts_at + interval '7 days') then
      insert into schedule (user_id, store_code, starts_at, ends_at, note, created_by)
      values (c.user_id, c.store_code, c.starts_at + interval '7 days', c.ends_at + interval '7 days', c.note, p_by);
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;

create or replace function public.a3_timeoff_request(p_user uuid, p_starts date, p_ends date, p_reason text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare t public.time_off;
begin
  if p_ends < p_starts then raise exception 'The last day has to be on or after the first day.'; end if;
  if p_starts < current_date - 1 then raise exception 'Pick days that haven''t happened yet.'; end if;
  insert into time_off (user_id, starts_on, ends_on, reason) values (p_user, p_starts, p_ends, nullif(trim(p_reason), '')) returning * into t;
  return to_jsonb(t);
end $$;

create or replace function public.a3_timeoff(p_user uuid default null) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(to_jsonb(t) || jsonb_build_object('name', (select coalesce(nullif(s.display_name, ''), s.name, split_part(s.email, '@', 1)) from staff s where s.user_id = t.user_id))
    order by (t.status = 'pending') desc, t.starts_on desc), '[]'::jsonb)
  from time_off t where (p_user is null or t.user_id = p_user) and t.ends_on >= current_date - 60
$$;

create or replace function public.a3_timeoff_decide(p_id bigint, p_status text, p_by text, p_user uuid default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare t public.time_off;
begin
  if p_status not in ('approved', 'denied', 'cancelled') then raise exception 'Unknown answer.'; end if;
  if p_user is not null and p_status <> 'cancelled' then raise exception 'You can only cancel your own request.'; end if;   -- p_user: the person asking
  update time_off set status = p_status, decided_by = p_by, decided_at = now()
   where id = p_id and (p_user is null or (user_id = p_user and status = 'pending')) returning * into t;
  if t.id is null then raise exception 'That request can''t be changed.'; end if;
  return to_jsonb(t);
end $$;

-- clock in, now aware of your scheduled shift (late after 5 minutes)
create or replace function public.a3_clock_in(p_user uuid, p_name text, p_store text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare st public.stores; s public.shifts; c public.schedule;
begin
  if exists (select 1 from shifts where user_id = p_user and clock_out is null) then raise exception 'You''re already clocked in.'; end if;
  select * into st from stores where code = p_store and active;
  if st.code is null then raise exception 'Pick a store.'; end if;
  select * into c from schedule where user_id = p_user and starts_at between now() - interval '6 hours' and now() + interval '3 hours'
     and ends_at > now() and not exists (select 1 from shifts x where x.scheduled_id = schedule.id) order by abs(extract(epoch from starts_at - now())) limit 1;
  insert into shifts (user_id, employee_name, store_code, store_name, clock_in, status, scheduled_id, late_minutes)
  values (p_user, coalesce(nullif(trim(p_name), ''), 'Staff'), st.code, 'Store #' || st.code || ' – ' || st.name, now(), 'active', c.id,
          case when c.id is not null and now() > c.starts_at + interval '5 minutes' then floor(extract(epoch from now() - c.starts_at) / 60)::int end)
  returning * into s;
  return public.a3_shift_json(s);
end $$;

create or replace function public.a3_shift_json(s public.shifts) returns jsonb language sql stable as $$
  select jsonb_build_object('id', s.id, 'user_id', s.user_id, 'name', s.employee_name, 'store_code', s.store_code, 'store', s.store_name,
    'clock_in', s.clock_in, 'clock_out', s.clock_out, 'breaks', s.breaks, 'note', s.note, 'forgot', s.forgot,
    'edited_by', s.edited_by, 'edited_at', s.edited_at, 'minutes', public.a3_minutes(s),
    'on_break', exists (select 1 from jsonb_array_elements(s.breaks) b where b->>'end' is null) and s.clock_out is null,
    'sales', coalesce(s.total_sales, 0), 'orders', coalesce(s.total_orders, 0),
    'scheduled_id', s.scheduled_id, 'late_minutes', s.late_minutes,
    'scheduled', (select jsonb_build_object('starts_at', c.starts_at, 'ends_at', c.ends_at) from public.schedule c where c.id = s.scheduled_id))
$$;

-- what the terminal needs when it opens, now with your schedule and pending requests
create or replace function public.a3_staff_state(p_user uuid, p_tz text default 'America/New_York') returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'shift', (select public.a3_shift_json(s) from shifts s where s.user_id = p_user and s.clock_out is null),
    'last_store', coalesce((select default_store from staff where user_id = p_user),
                           (select s.store_code from shifts s where s.user_id = p_user and s.store_code is not null order by s.clock_in desc limit 1)),
    'week_minutes', (select coalesce(sum(public.a3_minutes(s)), 0) from shifts s where s.user_id = p_user
                       and s.clock_in >= (date_trunc('week', now() at time zone p_tz) at time zone p_tz)),
    'stores', (select coalesce(jsonb_agg(jsonb_build_object('code', code, 'name', name, 'region', region) order by region, name), '[]'::jsonb) from stores where active),
    'upcoming', (select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'starts_at', c.starts_at, 'ends_at', c.ends_at, 'store_code', c.store_code, 'note', c.note) order by c.starts_at), '[]'::jsonb)
                   from (select * from schedule c where c.user_id = p_user and c.ends_at > now() order by c.starts_at limit 5) c),
    'pending_time_off', (select count(*) from time_off where status = 'pending'))
$$;

-- ============================================================ orders, payments, quotes
create or replace function public.a3_record_order(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare existing text; s public.shifts; oid text := p->>'order_id';
begin
  select order_id into existing from orders
   where (p->>'stripe_session_id' is not null and stripe_session_id = p->>'stripe_session_id')
      or (p->>'stripe_invoice_id' is not null and stripe_invoice_id = p->>'stripe_invoice_id') limit 1;
  if existing is not null then return jsonb_build_object('order_id', existing, 'created', false); end if;
  if (p->>'shift_id') is not null then select * into s from shifts where id = (p->>'shift_id')::bigint; end if;
  insert into orders (order_id, status, plan_type, tier, billing, config, items, amount_cents, total_price, currency, customer_name, customer_email,
                      source, staff_user_id, operator, store_name, shift_id, payment_method, notes,
                      stripe_session_id, stripe_subscription_id, stripe_customer_id, stripe_invoice_id,
                      company_name, customer_phone, customer_info, seats, quote_no, node_id, target_jurisdiction, promo_code, discount_amount)
  values (oid, 'ACTIVE', p->>'plan_type', p->>'tier', p->>'billing', (p->'config')::json, p->'items', (p->>'amount_cents')::int,
          to_char(coalesce((p->>'amount_cents')::numeric, 0) / 100, 'FM999999990.00'), upper(coalesce(p->>'currency', 'usd')),
          nullif(p->>'customer_name', ''), nullif(p->>'customer_email', ''), coalesce(p->>'source', 'web'), (p->>'staff_user_id')::uuid,
          coalesce(p->>'operator', 'Online store'), coalesce(s.store_name, case when coalesce(p->>'source', 'web') = 'web' then 'Online store' end), s.id,
          coalesce(p->>'payment_method', 'card'), p->>'notes',
          p->>'stripe_session_id', p->>'stripe_subscription_id', p->>'stripe_customer_id', p->>'stripe_invoice_id',
          nullif(p->>'company_name', ''), nullif(p->>'customer_phone', ''), p->'customer_info', (p->>'seats')::int, nullif(p->>'quote_no', ''),
          nullif(p->>'node_id', ''), nullif(p->>'target_jurisdiction', ''), nullif(upper(p->>'promo_code'), ''), coalesce((p->>'discount_cents')::numeric / 100, 0));
  if s.id is not null then
    update shifts set total_sales = coalesce(total_sales, 0) + coalesce((p->>'amount_cents')::numeric, 0) / 100,
                      total_orders = coalesce(total_orders, 0) + 1 where id = s.id;
  end if;
  if coalesce((p->>'amount_cents')::int, 0) > 0 then
    insert into payments (order_id, stripe_invoice_id, stripe_subscription_id, amount_cents, kind)
    values (oid, coalesce(p->>'first_invoice_id', 'first:' || oid), p->>'stripe_subscription_id', (p->>'amount_cents')::int, 'first')
    on conflict (stripe_invoice_id) do nothing;
  end if;
  if nullif(p->>'quote_no', '') is not null then
    update quotes set status = 'paid', order_id = oid, updated_at = now() where quote_no = p->>'quote_no';
  end if;
  if nullif(p->>'promo_code', '') is not null then
    update promotions set used_count = coalesce(used_count, 0) + 1 where code = upper(p->>'promo_code');
  end if;
  return jsonb_build_object('order_id', oid, 'created', true);
end $$;

-- a renewal (or any later invoice) on a subscription we know
create or replace function public.a3_record_payment(p_invoice text, p_subscription text, p_amount_cents int, p_kind text default 'renewal') returns jsonb
language plpgsql security definer set search_path = public as $$
declare oid text;
begin
  select order_id into oid from orders where stripe_subscription_id = p_subscription limit 1;
  if oid is null then return jsonb_build_object('recorded', false, 'reason', 'unknown subscription'); end if;
  insert into payments (order_id, stripe_invoice_id, stripe_subscription_id, amount_cents, kind)
  values (oid, p_invoice, p_subscription, p_amount_cents, p_kind) on conflict (stripe_invoice_id) do nothing;
  return jsonb_build_object('recorded', true, 'order_id', oid);
end $$;

create or replace function public.a3_order_json(o public.orders) returns jsonb language sql stable as $$
  select jsonb_build_object('order_id', o.order_id, 'created_at', o.created_at, 'status', o.status, 'plan', o.plan_type, 'tier', o.tier,
    'billing', o.billing, 'amount', public.a3_amount(o), 'customer_name', o.customer_name, 'customer_email', o.customer_email,
    'operator', o.operator, 'store', o.store_name, 'source', coalesce(o.source, 'legacy'), 'config', o.config,
    'models', (select coalesce(jsonb_agg(i->>'model'), '[]'::jsonb) from jsonb_array_elements(coalesce(o.items, '[]'::jsonb)) i),
    'subscription', o.stripe_subscription_id is not null,
    'company_name', o.company_name, 'customer_phone', o.customer_phone, 'customer_info', o.customer_info, 'seats', o.seats,
    'quote_no', o.quote_no, 'node_id', o.node_id, 'jurisdiction', o.target_jurisdiction, 'promo_code', o.promo_code,
    'discount', o.discount_amount, 'notes', o.notes,
    'paid_total', (select coalesce(sum(amount_cents), 0) / 100.0 from payments y where y.order_id = o.order_id),
    'payments', (select count(*) from payments y where y.order_id = o.order_id))
$$;

-- searches order number, email, name and company
create or replace function public.a3_orders(p_q text default '', p_limit int default 50) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.a3_order_json(o) order by o.created_at desc), '[]'::jsonb) from (
    select * from orders o
     where coalesce(trim(p_q), '') = '' or o.order_id ilike '%' || trim(p_q) || '%' or o.customer_email ilike '%' || trim(p_q) || '%'
        or o.customer_name ilike '%' || trim(p_q) || '%' or o.company_name ilike '%' || trim(p_q) || '%' or o.quote_no ilike '%' || trim(p_q) || '%'
     order by o.created_at desc limit least(greatest(coalesce(p_limit, 50), 1), 5000)) o
$$;

create or replace function public.a3_quote_json(q public.quotes) returns jsonb language sql stable as $$
  select to_jsonb(q) - 'stripe_session_id' - 'stripe_subscription_id' || jsonb_build_object('amount', q.amount_cents / 100.0)
$$;

create or replace function public.a3_quote_save(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare q public.quotes;
begin
  if (p->>'quote_no') is not null and exists (select 1 from quotes where quote_no = p->>'quote_no') then
    if exists (select 1 from quotes where quote_no = p->>'quote_no' and status = 'paid') and coalesce(p->>'status', 'paid') <> 'paid' then
      raise exception 'That quote is already paid.'; end if;
    update quotes set plan = coalesce(p->>'plan', plan), tier = coalesce(p->>'tier', tier), seats = coalesce((p->>'seats')::int, seats),
      interval = coalesce(p->>'interval', interval), amount_cents = coalesce((p->>'amount_cents')::int, amount_cents),
      config = coalesce(p->'config', config), items = coalesce(p->'items', items), customer = coalesce(p->'customer', customer),
      notes = case when p ? 'notes' then p->>'notes' else notes end, valid_until = coalesce((p->>'valid_until')::date, valid_until),
      status = coalesce(p->>'status', status), delivery = coalesce(p->>'delivery', delivery), url = coalesce(p->>'url', url),
      stripe_session_id = coalesce(p->>'stripe_session_id', stripe_session_id), stripe_invoice_id = coalesce(p->>'stripe_invoice_id', stripe_invoice_id),
      stripe_subscription_id = coalesce(p->>'stripe_subscription_id', stripe_subscription_id), order_id = coalesce(p->>'order_id', order_id), updated_at = now()
    where quote_no = p->>'quote_no' returning * into q;
  else
    insert into quotes (quote_no, plan, tier, seats, interval, amount_cents, config, items, customer, notes, valid_until, created_by, created_by_id)
    values (p->>'quote_no', p->>'plan', p->>'tier', (p->>'seats')::int, coalesce(p->>'interval', 'month'), coalesce((p->>'amount_cents')::int, 0),
            coalesce(p->'config', '{}'), coalesce(p->'items', '[]'), coalesce(p->'customer', '{}'), p->>'notes',
            coalesce((p->>'valid_until')::date, current_date + 30), p->>'created_by', (p->>'created_by_id')::uuid)
    returning * into q;
  end if;
  return public.a3_quote_json(q);
end $$;

create or replace function public.a3_quotes(p_status text default null) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.a3_quote_json(q) order by q.created_at desc), '[]'::jsonb)
  from (select * from quotes where p_status is null or status = p_status order by created_at desc limit 300) q
$$;

create or replace function public.a3_quote(p_no text) returns jsonb
language sql stable security definer set search_path = public as $$
  select public.a3_quote_json(q) || jsonb_build_object('stripe_subscription_id', q.stripe_subscription_id) from quotes q where q.quote_no = upper(trim(p_no))
$$;

-- ============================================================ promotions
create or replace function public.a3_promo_json(x public.promotions) returns jsonb language sql stable as $$
  select jsonb_build_object('id', x.id, 'code', x.code, 'type', x.discount_type, 'value', x.discount_value, 'duration', x.duration,
    'duration_months', x.duration_months, 'description', x.description, 'plans', x.applicable_plans, 'tiers', x.applicable_tiers,
    'min_total', x.min_order_total, 'starts', x.start_date, 'ends', x.end_date, 'active', x.is_active, 'limit', x.usage_limit,
    'used', coalesce(x.used_count, 0), 'created_by', x.created_by, 'created_at', x.created_at, 'stripe_promo_id', x.stripe_promo_id,
    'live', x.is_active and (x.end_date is null or x.end_date > now()) and (x.start_date is null or x.start_date <= now())
            and (x.usage_limit is null or coalesce(x.used_count, 0) < x.usage_limit))
$$;
create or replace function public.a3_promos() returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.a3_promo_json(x) order by x.is_active desc, x.created_at desc), '[]'::jsonb) from promotions x
$$;
create or replace function public.a3_promo(p_code text) returns jsonb language sql stable security definer set search_path = public as $$
  select public.a3_promo_json(x) || jsonb_build_object('stripe_coupon_id', x.stripe_coupon_id) from promotions x where x.code = upper(trim(p_code))
$$;
create or replace function public.a3_promo_save(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare x public.promotions; c text := upper(trim(p->>'code'));
begin
  if (p->>'id') is not null then
    update promotions set is_active = coalesce((p->>'active')::boolean, is_active), description = coalesce(p->>'description', description),
      end_date = case when p ? 'ends' then (p->>'ends')::timestamptz else end_date end, usage_limit = case when p ? 'limit' then (p->>'limit')::int else usage_limit end
     where id = (p->>'id')::bigint returning * into x;
  else
    if c !~ '^[A-Z0-9_-]{3,30}$' then raise exception 'Codes are 3 to 30 letters, numbers, - or _.'; end if;
    if exists (select 1 from promotions where code = c) then raise exception 'That code already exists.'; end if;
    insert into promotions (code, discount_type, discount_value, duration, duration_months, description, applicable_plans, applicable_tiers,
                            min_order_total, start_date, end_date, is_active, usage_limit, used_count, stripe_coupon_id, stripe_promo_id, created_by)
    values (c, p->>'type', (p->>'value')::numeric, coalesce(p->>'duration', 'once'), (p->>'duration_months')::int, p->>'description',
            (select array_agg(v) from jsonb_array_elements_text(coalesce(p->'plans', '[]')) v), (select array_agg(v) from jsonb_array_elements_text(coalesce(p->'tiers', '[]')) v),
            coalesce((p->>'min_total')::numeric, 0), coalesce((p->>'starts')::timestamptz, now()), (p->>'ends')::timestamptz, true, (p->>'limit')::int, 0,
            p->>'stripe_coupon_id', p->>'stripe_promo_id', p->>'created_by')
    returning * into x;
  end if;
  return public.a3_promo_json(x);
end $$;

-- ============================================================ sales (all time)
-- p_user: just one person's sales (null = everyone)
create or replace function public.a3_sales(p_user uuid default null, p_tz text default 'America/New_York') returns jsonb
language sql stable security definer set search_path = public as $$
  with o as (select * from orders x where public.a3_counts(x) and (p_user is null or x.staff_user_id = p_user)),
       pay as (select y.*, x.plan_type, x.tier from payments y join orders x on x.order_id = y.order_id
                where public.a3_counts(x) and (p_user is null or x.staff_user_id = p_user))
  select jsonb_build_object(
    'all_time', jsonb_build_object(
       'revenue', coalesce((select sum(amount_cents) from pay), 0) / 100.0 + coalesce((select sum(public.a3_amount(x)) from o x where x.stripe_session_id is null and x.stripe_invoice_id is null), 0),
       'orders', (select count(*) from o), 'paid_orders', (select count(*) from o x where coalesce(x.amount_cents, 0) > 0 or coalesce(x.source, 'legacy') = 'legacy'),
       'comp_orders', (select count(*) from o where source = 'comp'), 'renewals', (select count(*) from pay where kind = 'renewal'),
       'first_order', (select min(created_at) from o)),
    'this_month', (select coalesce(sum(amount_cents), 0) / 100.0 from pay where paid_at >= (date_trunc('month', now() at time zone p_tz) at time zone p_tz)),
    'mrr', (select coalesce(sum(case when billing = 'year' then amount_cents / 12.0 else amount_cents end), 0) / 100.0 from o
              where stripe_subscription_id is not null and upper(status) = 'ACTIVE'),
    'active_subscriptions', (select count(*) from o where stripe_subscription_id is not null and upper(status) = 'ACTIVE'),
    'months', (select coalesce(jsonb_agg(jsonb_build_object('month', to_char(m, 'YYYY-MM'),
                 'revenue', (select coalesce(sum(amount_cents), 0) / 100.0 from pay where paid_at >= m at time zone p_tz and paid_at < (m + interval '1 month') at time zone p_tz)
                          + (select coalesce(sum(public.a3_amount(x)), 0) from o x where x.stripe_session_id is null and x.stripe_invoice_id is null
                              and x.created_at >= m at time zone p_tz and x.created_at < (m + interval '1 month') at time zone p_tz),
                 'orders', (select count(*) from o x where x.created_at >= m at time zone p_tz and x.created_at < (m + interval '1 month') at time zone p_tz)) order by m), '[]'::jsonb)
               from generate_series(date_trunc('month', now() at time zone p_tz) - interval '11 months', date_trunc('month', now() at time zone p_tz), interval '1 month') m),
    'by_plan', (select coalesce(jsonb_agg(jsonb_build_object('key', k, 'orders', n, 'revenue', r) order by r desc), '[]'::jsonb)
                  from (select coalesce(plan_type, '—') k, count(*) n, sum(public.a3_amount(x)) r from o x group by 1) t),
    'by_tier', (select coalesce(jsonb_agg(jsonb_build_object('key', k, 'orders', n, 'revenue', r) order by r desc), '[]'::jsonb)
                  from (select coalesce(tier, lower(config->>'service_tier'), '—') k, count(*) n, sum(public.a3_amount(x)) r from o x group by 1) t),
    'by_source', (select coalesce(jsonb_agg(jsonb_build_object('key', k, 'orders', n, 'revenue', r) order by r desc), '[]'::jsonb)
                  from (select coalesce(source, 'legacy') k, count(*) n, sum(public.a3_amount(x)) r from o x group by 1) t),
    'top_staff', (select coalesce(jsonb_agg(jsonb_build_object('name', k, 'orders', n, 'revenue', r) order by r desc), '[]'::jsonb)
                  from (select coalesce(operator, '—') k, count(*) n, sum(public.a3_amount(x)) r from o x where coalesce(source, 'legacy') not in ('web') group by 1 order by 3 desc limit 10) t),
    'top_stores', (select coalesce(jsonb_agg(jsonb_build_object('name', k, 'orders', n, 'revenue', r) order by r desc), '[]'::jsonb)
                  from (select coalesce(store_name, '—') k, count(*) n, sum(public.a3_amount(x)) r from o x group by 1 order by 3 desc limit 10) t))
$$;

-- ============================================================ settings & stores
create or replace function public.a3_settings() returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_object_agg(key, value), '{}'::jsonb) from settings
$$;
create or replace function public.a3_setting_set(p_key text, p_value jsonb, p_by text) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if p_key not in ('store', 'business', 'goals') then raise exception 'Unknown setting.'; end if;
  insert into settings (key, value, updated_by, updated_at) values (p_key, p_value, p_by, now())
  on conflict (key) do update set value = excluded.value, updated_by = excluded.updated_by, updated_at = now();
  return public.a3_settings();
end $$;
create or replace function public.a3_store_save(p_code text, p_name text, p_region text, p_active boolean) returns jsonb
language plpgsql security definer set search_path = public as $$
declare st public.stores;
begin
  if p_code !~ '^[0-9]{4}$' then raise exception 'Store numbers are 4 digits.'; end if;
  insert into stores (code, name, region, active) values (p_code, trim(p_name), upper(coalesce(nullif(p_region, ''), 'A')), coalesce(p_active, true))
  on conflict (code) do update set name = coalesce(nullif(trim(excluded.name), ''), stores.name), region = excluded.region, active = excluded.active
  returning * into st;
  return to_jsonb(st);
end $$;
create or replace function public.a3_stores_all() returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(to_jsonb(s) order by s.region, s.name), '[]'::jsonb) from stores s
$$;

