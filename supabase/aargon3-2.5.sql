-- aARgon3 2.5: deals (automatic offers shown on the home page), codes that switch themselves off when they expire,
-- bringing the old aARgon3 promo codes into the Stripe system, batches of generated codes, and a fuller customer portal.
-- Run once in the aARgon3 & Mexel Backend project's SQL Editor, after aargon3-2.4.sql. Safe to run again.

-- ============================================================ deals: no code needed, applied to every order they fit
create table if not exists public.deals (
  id bigint generated by default as identity primary key,
  name text not null,                           -- staff name, e.g. "Black Friday Plus bundle"
  headline text not null,                       -- what customers see, e.g. "Get Neodela free with Plus"
  description text,
  kind text not null check (kind in ('percent', 'amount', 'models', 'chip', 'seats')),
  value numeric,                                -- percent or dollars off (percent / amount); extra people (seats)
  duration text not null default 'once' check (duration in ('once', 'repeating', 'forever')),   -- price deals: first payment, N months, or every payment
  duration_months integer,
  models text[],                                -- bonus models (models)
  chip text,                                    -- upgraded chip (chip)
  plans text[], tiers text[], billing text[],   -- which orders it fits (empty = any)
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  active boolean not null default true,
  featured boolean not null default true,       -- shown on the home page
  stripe_coupon_id text,
  used_count integer not null default 0,
  usage_limit integer,
  ended_reason text,                            -- 'expired' / 'used up' (switched off automatically) or 'manual'
  ended_at timestamptz,
  created_by text,
  created_at timestamptz not null default now()
);
alter table public.deals enable row level security;
revoke all on public.deals from anon, authenticated;

alter table public.orders add column if not exists deals jsonb;   -- [{ id, headline, kind }] that applied to this order

-- promotions: why a code stopped working, and codes made together by the generator
alter table public.promotions add column if not exists ended_reason text;
alter table public.promotions add column if not exists ended_at timestamptz;
alter table public.promotions add column if not exists batch text;
alter table public.promotions add column if not exists migrated_at timestamptz;

create or replace function public.a3_deal_json(d public.deals) returns jsonb language sql stable as $$
  select to_jsonb(d) - 'stripe_coupon_id' || jsonb_build_object('has_coupon', d.stripe_coupon_id is not null,
    'live', d.active and d.starts_at <= now() and (d.ends_at is null or d.ends_at > now()) and (d.usage_limit is null or d.used_count < d.usage_limit))
$$;

create or replace function public.a3_deals() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.a3_deal_json(d) order by d.active desc, d.created_at desc), '[]'::jsonb) from deals d
$$;

-- what checkout needs: live deals, with their Stripe coupon
create or replace function public.a3_deals_live() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.a3_deal_json(d) || jsonb_build_object('stripe_coupon_id', d.stripe_coupon_id) order by d.created_at), '[]'::jsonb)
  from deals d where d.active and d.starts_at <= now() and (d.ends_at is null or d.ends_at > now()) and (d.usage_limit is null or d.used_count < d.usage_limit)
$$;

create or replace function public.a3_deal_save(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare d public.deals; arr text := 'select array_agg(v) from jsonb_array_elements_text(coalesce($1, ''[]'')) v';
begin
  if nullif(p->>'id', '') is not null then
    update deals set
      active = coalesce((p->>'active')::boolean, active),
      featured = coalesce((p->>'featured')::boolean, featured),
      headline = coalesce(p->>'headline', headline), description = coalesce(p->>'description', description),
      ends_at = case when p ? 'ends_at' then (p->>'ends_at')::timestamptz else ends_at end,
      ended_reason = case when (p->>'active')::boolean is false then 'manual' when (p->>'active')::boolean then null else ended_reason end,
      ended_at = case when (p->>'active')::boolean is false then now() when (p->>'active')::boolean then null else ended_at end
    where id = (p->>'id')::bigint returning * into d;
    if d.id is null then raise exception 'No deal with that id.'; end if;
  else
    insert into deals (name, headline, description, kind, value, duration, duration_months, models, chip, plans, tiers, billing, starts_at, ends_at, featured, stripe_coupon_id, usage_limit, created_by)
    values (p->>'name', p->>'headline', p->>'description', p->>'kind', (p->>'value')::numeric, coalesce(p->>'duration', 'once'), (p->>'duration_months')::int,
      (select array_agg(v) from jsonb_array_elements_text(coalesce(p->'models', '[]')) v), p->>'chip',
      (select array_agg(v) from jsonb_array_elements_text(coalesce(p->'plans', '[]')) v), (select array_agg(v) from jsonb_array_elements_text(coalesce(p->'tiers', '[]')) v),
      (select array_agg(v) from jsonb_array_elements_text(coalesce(p->'billing', '[]')) v),
      coalesce((p->>'starts_at')::timestamptz, now()), (p->>'ends_at')::timestamptz, coalesce((p->>'featured')::boolean, true), p->>'stripe_coupon_id', (p->>'limit')::int, p->>'by')
    returning * into d;
  end if;
  return public.a3_deal_json(d);
end $$;

create or replace function public.a3_deals_used(p_ids bigint[]) returns void
language sql security definer set search_path = public as $$
  update deals set used_count = used_count + 1 where id = any(p_ids)
$$;

-- ============================================================ promo JSON: plus why it ended, batch, and whether it still needs Stripe
create or replace function public.a3_promo_json(x public.promotions) returns jsonb language sql stable as $$
  select jsonb_build_object('id', x.id, 'code', x.code, 'type', x.discount_type, 'value', x.discount_value, 'duration', x.duration,
    'duration_months', x.duration_months, 'description', x.description, 'plans', x.applicable_plans, 'tiers', x.applicable_tiers,
    'min_total', x.min_order_total, 'starts', x.start_date, 'ends', x.end_date, 'active', x.is_active, 'limit', x.usage_limit,
    'used', coalesce(x.used_count, 0), 'created_by', x.created_by, 'created_at', x.created_at, 'stripe_promo_id', x.stripe_promo_id,
    'live', x.is_active and (x.end_date is null or x.end_date > now()) and (x.start_date is null or x.start_date <= now())
            and (x.usage_limit is null or coalesce(x.used_count, 0) < x.usage_limit))
  || jsonb_build_object('ended_reason', x.ended_reason, 'ended_at', x.ended_at, 'batch', x.batch, 'old', x.stripe_promo_id is null, 'migrated_at', x.migrated_at)
$$;

-- switching a code on or off by hand records why
create or replace function public.a3_promo_save(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare x public.promotions; c text := upper(trim(p->>'code'));
begin
  if (p->>'id') is not null then
    update promotions set is_active = coalesce((p->>'active')::boolean, is_active), description = coalesce(p->>'description', description),
      end_date = case when p ? 'ends' then (p->>'ends')::timestamptz else end_date end, usage_limit = case when p ? 'limit' then (p->>'limit')::int else usage_limit end,
      ended_reason = case when (p->>'active')::boolean is false then 'manual' when (p->>'active')::boolean then null else ended_reason end,
      ended_at = case when (p->>'active')::boolean is false then now() when (p->>'active')::boolean then null else ended_at end
     where id = (p->>'id')::bigint returning * into x;
  else
    if c !~ '^[A-Z0-9_-]{3,30}$' then raise exception 'Codes are 3 to 30 letters, numbers, - or _.'; end if;
    if exists (select 1 from promotions where code = c) then raise exception 'That code already exists.'; end if;
    insert into promotions (code, discount_type, discount_value, duration, duration_months, description, applicable_plans, applicable_tiers,
                            min_order_total, start_date, end_date, is_active, usage_limit, used_count, stripe_coupon_id, stripe_promo_id, created_by, batch)
    values (c, p->>'type', (p->>'value')::numeric, coalesce(p->>'duration', 'once'), (p->>'duration_months')::int, p->>'description',
            (select array_agg(v) from jsonb_array_elements_text(coalesce(p->'plans', '[]')) v), (select array_agg(v) from jsonb_array_elements_text(coalesce(p->'tiers', '[]')) v),
            coalesce((p->>'min_total')::numeric, 0), coalesce((p->>'starts')::timestamptz, now()), (p->>'ends')::timestamptz, true, (p->>'limit')::int, 0,
            p->>'stripe_coupon_id', p->>'stripe_promo_id', p->>'created_by', p->>'batch')
    returning * into x;
  end if;
  return public.a3_promo_json(x);
end $$;

-- an old aARgon3 code, rewritten for the new system: tidy code / type / plans / tiers, link the Stripe coupon + promotion code
create or replace function public.a3_promo_upgrade(p_id bigint, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare x public.promotions;
begin
  update promotions set
    code = coalesce(nullif(upper(trim(p->>'code')), ''), code),
    discount_type = coalesce(p->>'type', discount_type), discount_value = coalesce((p->>'value')::numeric, discount_value),
    duration = coalesce(p->>'duration', duration, 'once'),
    applicable_plans = case when p ? 'plans' then (select array_agg(v) from jsonb_array_elements_text(p->'plans') v) else applicable_plans end,
    applicable_tiers = case when p ? 'tiers' then (select array_agg(v) from jsonb_array_elements_text(p->'tiers') v) else applicable_tiers end,
    description = coalesce(p->>'description', description),
    stripe_coupon_id = coalesce(p->>'stripe_coupon_id', stripe_coupon_id), stripe_promo_id = coalesce(p->>'stripe_promo_id', stripe_promo_id),
    is_active = coalesce((p->>'active')::boolean, is_active),
    ended_reason = case when (p->>'active')::boolean is false then coalesce(p->>'ended_reason', 'expired') else ended_reason end,
    ended_at = case when (p->>'active')::boolean is false then coalesce(ended_at, now()) else ended_at end,
    migrated_at = now()
  where id = p_id returning * into x;
  if x.id is null then raise exception 'No promotion with that id.'; end if;
  return public.a3_promo_json(x);
end $$;

-- ============================================================ every hour (pg_cron from 2.4): finished gifts, plus codes and deals that ran out
create or replace function public.a3_expire() returns integer
language plpgsql security definer set search_path = public as $$
declare n int; m int; k int;
begin
  update orders set status = 'EXPIRED', history = history || jsonb_build_array(jsonb_build_object('kind', 'expired', 'at', now()))
  where expires_at is not null and expires_at < now() and status in ('ACTIVE', 'PAID');
  get diagnostics n = row_count;
  update promotions set is_active = false, ended_at = now(),
    ended_reason = case when end_date is not null and end_date <= now() then 'expired' else 'used up' end
  where is_active and ((end_date is not null and end_date <= now()) or (usage_limit is not null and coalesce(used_count, 0) >= usage_limit));
  get diagnostics m = row_count;
  update deals set active = false, ended_at = now(), ended_reason = case when ends_at is not null and ends_at <= now() then 'expired' else 'used up' end
  where active and ((ends_at is not null and ends_at <= now()) or (usage_limit is not null and used_count >= usage_limit));
  get diagnostics k = row_count;
  return n + m + k;
end $$;

-- ============================================================ customer portal: they can fix their own contact details
create or replace function public.a3_order_contact(p_order text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare o public.orders;
begin
  update orders set
    customer_name = coalesce(nullif(trim(concat_ws(' ', p->>'first', p->>'last')), ''), customer_name),
    customer_phone = case when p ? 'phone' then p->>'phone' else customer_phone end,
    company_name = case when p ? 'company' then p->>'company' else company_name end,
    customer_info = coalesce(customer_info, '{}'::jsonb) || (p - 'email'),
    history = history || jsonb_build_array(jsonb_build_object('kind', 'contact', 'by', 'customer', 'at', now()))
  where order_id = p_order returning * into o;
  if o.order_id is null then raise exception 'Order not found.'; end if;
  return public.a3_order_json(o);
end $$;

-- order JSON gains the deals that applied (everything else as in 2.4)
create or replace function public.a3_order_json(o public.orders) returns jsonb language sql stable as $$
  select jsonb_build_object('order_id', o.order_id, 'created_at', o.created_at, 'status', o.status, 'plan', o.plan_type, 'tier', o.tier,
    'billing', o.billing, 'amount', public.a3_amount(o), 'customer_name', o.customer_name, 'customer_email', o.customer_email,
    'operator', o.operator, 'store', o.store_name, 'source', coalesce(o.source, 'legacy'), 'config', o.config,
    'models', (select coalesce(jsonb_agg(i->>'model'), '[]'::jsonb) from jsonb_array_elements(coalesce(o.items, '[]'::jsonb)) i),
    'subscription', o.stripe_subscription_id is not null,
    'company_name', o.company_name, 'customer_phone', o.customer_phone, 'customer_info', o.customer_info, 'seats', o.seats,
    'quote_no', o.quote_no, 'node_id', o.node_id, 'jurisdiction', o.target_jurisdiction, 'promo_code', o.promo_code,
    'discount', o.discount_amount, 'notes', o.notes,
    'paid_total', (select coalesce(sum(amount_cents), 0) / 100.0 from payments y where y.order_id = o.order_id),
    'payments', (select count(*) from payments y where y.order_id = o.order_id))
  || jsonb_build_object('region', o.region, 'tax', o.tax_cents / 100.0, 'current_period_end', o.current_period_end, 'cancel_at', o.cancel_at,
    'paused_until', o.paused_until, 'expires_at', o.expires_at, 'referral_code', o.referral_code, 'referred_by', o.referred_by,
    'gift', o.gift, 'history', o.history, 'stripe_customer', o.stripe_customer_id is not null,
    'referrals', (select count(*) from referrals r where r.referrer_order = o.order_id),
    'referral_credit', (select coalesce(sum(credit_cents), 0) / 100.0 from referrals r where r.referrer_order = o.order_id))
  || jsonb_build_object('deals', o.deals)
$$;

create or replace function public.a3_order_patch_deals(p_order text, p_deals jsonb) returns void
language sql security definer set search_path = public as $$
  update orders set deals = p_deals where order_id = p_order
$$;

-- ============================================================ only the Edge Functions (service key) may call these
do $$
declare f text;
begin
  foreach f in array array['a3_deals()', 'a3_deals_live()', 'a3_deal_save(jsonb)', 'a3_deals_used(bigint[])', 'a3_promo_save(jsonb)', 'a3_promo_upgrade(bigint, jsonb)',
    'a3_expire()', 'a3_order_contact(text, jsonb)', 'a3_order_patch_deals(text, jsonb)']
  loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
    execute format('grant execute on function public.%s to service_role', f);
  end loop;
end $$;
