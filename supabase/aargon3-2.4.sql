$$;

-- after a3_record_order: fill in what 2.4 adds (only these columns can be patched)
create or replace function public.a3_order_patch(p_order text, p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare o public.orders;
begin
  update orders set
    region = case when p ? 'region' then p->>'region' else region end,
    tax_cents = case when p ? 'tax_cents' then coalesce((p->>'tax_cents')::int, 0) else tax_cents end,
    current_period_end = case when p ? 'current_period_end' then (p->>'current_period_end')::timestamptz else current_period_end end,
    cancel_at = case when p ? 'cancel_at' then (p->>'cancel_at')::timestamptz else cancel_at end,
    paused_until = case when p ? 'paused_until' then (p->>'paused_until')::timestamptz else paused_until end,
    expires_at = case when p ? 'expires_at' then (p->>'expires_at')::timestamptz else expires_at end,
    referral_code = coalesce(referral_code, p->>'referral_code'),
    referred_by = case when p ? 'referred_by' then p->>'referred_by' else referred_by end,
    gift = case when p ? 'gift' then p->'gift' else gift end,
    gift_code = case when p ? 'gift_code' then p->>'gift_code' else gift_code end,
    status = case when p ? 'status' then upper(p->>'status') else status end,
    -- plan changes
    tier = case when p ? 'tier' then p->>'tier' else tier end,
    plan_type = case when p ? 'plan_type' then p->>'plan_type' else plan_type end,
    billing = case when p ? 'billing' then p->>'billing' else billing end,
    config = case when p ? 'config' then (p->'config')::json else config end,
    items = case when p ? 'items' then p->'items' else items end,
    seats = case when p ? 'seats' then (p->>'seats')::int else seats end,
    amount_cents = case when p ? 'amount_cents' then (p->>'amount_cents')::int else amount_cents end,
    history = case when p ? 'event' then history || jsonb_build_array(p->'event' || jsonb_build_object('at', now())) else history end
  where order_id = p_order returning * into o;
  if o.order_id is null then raise exception 'Order not found.'; end if;
  return public.a3_order_json(o);
end $$;

-- Stripe told us about a subscription change (webhook): status, renewal date, pause, cancel-at
create or replace function public.a3_subscription_sync(p_subscription text, p jsonb) returns integer
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  update orders set
    status = coalesce(upper(p->>'status'), status),
    current_period_end = coalesce((p->>'current_period_end')::timestamptz, current_period_end),
    cancel_at = case when p ? 'cancel_at' then (p->>'cancel_at')::timestamptz else cancel_at end,
    paused_until = case when p ? 'paused_until' then (p->>'paused_until')::timestamptz else paused_until end
  where stripe_subscription_id = p_subscription and status <> 'GIFT';
  get diagnostics n = row_count; return n;
end $$;

-- ============================================================ customer portal
-- order number + email must both match. Wrong guesses are counted per IP and per order number.
create or replace function public.a3_portal_attempt(p_keys text[], p_failed boolean) returns integer
language plpgsql security definer set search_path = public as $$
declare k text; worst int := 0; n int;
begin
  delete from portal_attempts where at < now() - interval '1 day';
  foreach k in array p_keys loop
    if p_failed then insert into portal_attempts (key) values (k); end if;
    select count(*) into n from portal_attempts where key = k and at > now() - interval '1 hour';
    worst := greatest(worst, n);
  end loop;
  return worst;
end $$;

create or replace function public.a3_portal_order(p_order text, p_email text) returns jsonb
language sql stable security definer set search_path = public as $$
  select public.a3_order_json(o) from orders o
  where o.order_id = upper(trim(p_order)) and o.status <> 'GIFT'
    and lower(trim(p_email)) in (lower(o.customer_email), lower(coalesce(o.customer_info->>'billing_email', '')), lower(coalesce(o.gift->>'to_email', '')))
$$;

-- ============================================================ gifts
create or replace function public.a3_gift(p_code text) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('code', o.gift_code, 'plan', o.plan_type, 'tier', o.tier, 'months', (o.gift->>'months')::int, 'claimed', o.status <> 'GIFT',
    'from_name', o.gift->>'from_name', 'to_name', o.gift->>'to_name', 'message', o.gift->>'message', 'config', o.config)
  from orders o where o.gift_code = upper(trim(p_code))
$$;

-- the person who got the gift claims it: the order becomes theirs, their months start now
create or replace function public.a3_gift_claim(p_code text, p_customer jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare o public.orders;
begin
  select * into o from orders where gift_code = upper(trim(p_code)) for update;
  if o.order_id is null then raise exception 'That gift code isn''t right. Check it and try again.'; end if;
  if o.status <> 'GIFT' then raise exception 'That gift has already been claimed.'; end if;
  update orders set status = 'ACTIVE',
    customer_name = trim(concat_ws(' ', p_customer->>'first', p_customer->>'last')), customer_email = lower(p_customer->>'email'),
    customer_phone = p_customer->>'phone', company_name = p_customer->>'company', customer_info = p_customer,
    expires_at = now() + make_interval(months => coalesce((o.gift->>'months')::int, 1)),
    gift = o.gift || jsonb_build_object('claimed_at', now()),
    history = history || jsonb_build_array(jsonb_build_object('kind', 'gift_claimed', 'by', p_customer->>'email', 'at', now()))
  where order_id = o.order_id returning * into o;
  return public.a3_order_json(o);
end $$;

-- gifts whose months have run out (and anything else past expires_at)
create or replace function public.a3_expire() returns integer
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  update orders set status = 'EXPIRED', history = history || jsonb_build_array(jsonb_build_object('kind', 'expired', 'at', now()))
  where expires_at is not null and expires_at < now() and status in ('ACTIVE', 'PAID');
  get diagnostics n = row_count; return n;
end $$;

-- ============================================================ referrals
create or replace function public.a3_referrer(p_code text) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('order_id', o.order_id, 'email', lower(o.customer_email), 'customer', o.stripe_customer_id, 'subscription', o.stripe_subscription_id,
    'plan', o.plan_type, 'tier', o.tier, 'status', o.status, 'name', o.customer_name,
    'this_year', (select count(*) from referrals r where r.code = o.referral_code and r.created_at > now() - interval '1 year' and r.status = 'credited'))
  from orders o where o.referral_code = upper(trim(p_code)) and o.status in ('ACTIVE', 'PAID', 'PAUSED')
$$;

create or replace function public.a3_referral_record(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare r public.referrals;
begin
  insert into referrals (code, referrer_order, new_order, new_email, credit_cents, stripe_txn_id, status)
  values (upper(p->>'code'), p->>'referrer_order', p->>'new_order', p->>'new_email', coalesce((p->>'credit_cents')::int, 0), p->>'stripe_txn_id', coalesce(p->>'status', 'credited'))
  on conflict (new_order) do nothing returning * into r;
  return case when r.id is null then jsonb_build_object('recorded', false) else to_jsonb(r) || jsonb_build_object('recorded', true) end;
end $$;

create or replace function public.a3_referrals(p_limit integer) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(to_jsonb(r) || jsonb_build_object('referrer_name', (select customer_name from orders where order_id = r.referrer_order)) order by r.created_at desc), '[]'::jsonb)
  from (select * from referrals order by created_at desc limit least(coalesce(p_limit, 100), 500)) r
$$;

-- ============================================================ abandoned checkouts
create or replace function public.a3_abandoned_save(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare a public.abandoned;
begin
  -- they came back and bought with the same email in the meantime? then no reminder
  if exists (select 1 from orders where lower(customer_email) = lower(p->>'email') and created_at > now() - interval '2 days') then
    return jsonb_build_object('saved', false, 'reason', 'already bought');
  end if;
  insert into abandoned (session_id, order_id, email, name, label, amount_cents, link)
  values (p->>'session_id', p->>'order_id', lower(p->>'email'), p->>'name', p->>'label', (p->>'amount_cents')::int, p->>'link')
  on conflict (session_id) do nothing returning * into a;
  return case when a.session_id is null then jsonb_build_object('saved', false, 'reason', 'seen') else to_jsonb(a) || jsonb_build_object('saved', true) end;
end $$;

create or replace function public.a3_abandoned_mark(p_session text, p_error text) returns void
language sql security definer set search_path = public as $$
  update abandoned set emailed_at = case when p_error is null then now() else emailed_at end, email_error = p_error where session_id = p_session
$$;

create or replace function public.a3_abandoned(p_limit integer) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(to_jsonb(a) || jsonb_build_object('recovered', exists (select 1 from orders o where lower(o.customer_email) = a.email and o.created_at > a.created_at))
    order by a.created_at desc), '[]'::jsonb)
  from (select * from abandoned order by created_at desc limit least(coalesce(p_limit, 100), 500)) a
$$;

-- ============================================================ store hours and closures
create or replace function public.a3_stores_public() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'stores', coalesce((select jsonb_agg(jsonb_build_object('code', code, 'name', name, 'region', region, 'hours', hours) order by region, code) from stores where active), '[]'::jsonb),
    'closures', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'store_code', store_code, 'starts_on', starts_on, 'ends_on', ends_on, 'reason', reason) order by starts_on)
      from closures where ends_on >= current_date - 1), '[]'::jsonb))
$$;

create or replace function public.a3_store_hours(p_code text, p_hours jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  update stores set hours = p_hours where code = p_code;
  if not found then raise exception 'No store #%.', p_code; end if;
  return public.a3_stores_public();
end $$;

create or replace function public.a3_closure_save(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if nullif(p->>'store_code', '') is not null and not exists (select 1 from stores where code = p->>'store_code') then raise exception 'No store #%.', p->>'store_code'; end if;
  if (p->>'ends_on')::date < (p->>'starts_on')::date then raise exception 'The closure has to end on or after the day it starts.'; end if;
  if nullif(p->>'id', '') is null then
    insert into closures (store_code, starts_on, ends_on, reason, created_by)
    values (nullif(p->>'store_code', ''), (p->>'starts_on')::date, (p->>'ends_on')::date, left(p->>'reason', 120), p->>'by');
  else
    update closures set store_code = nullif(p->>'store_code', ''), starts_on = (p->>'starts_on')::date, ends_on = (p->>'ends_on')::date, reason = left(p->>'reason', 120)
    where id = (p->>'id')::bigint;
  end if;
  return public.a3_stores_public();
end $$;

create or replace function public.a3_closure_delete(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
begin delete from closures where id = p_id; return public.a3_stores_public(); end $$;

-- ============================================================ hourly: expire finished gifts (needs pg_cron; skipped if it isn't available)
do $$
begin
  create extension if not exists pg_cron;
  perform cron.unschedule('aargon3-expire') where exists (select 1 from cron.job where jobname = 'aargon3-expire');
  perform cron.schedule('aargon3-expire', '7 * * * *', 'select public.a3_expire()');
exception when others then
  raise notice 'pg_cron is not available, so finished gifts are expired when staff open the terminal instead (%).', sqlerrm;
end $$;

