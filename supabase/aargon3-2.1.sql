-- Adds
--   • staff: aARgon3's own staff list with roles (owner / manager / employee), profiles, pay rates, on/off switch.
--     Nexus admins are added automatically the first time they sign in; the owner can also add anyone by email.
--   • schedule + time off: managers assign shifts; staff request days off; clock-in knows if you're late.
--   • quotes: custom orders and Enterprise quotes (custom price, seats, models), paid by link or emailed invoice.
--   • payments: every Stripe payment, including monthly/yearly renewals, so all-time sales are real.
--   • promotions: promo codes, mirrored to Stripe.
--   • settings: store open/closed, business details, sales goal.
--   • orders: company and contact details (business name, the person placing the order, phone, node, jurisdiction).

-- ============================================================ tables
create table if not exists public.staff (
  id bigint generated by default as identity primary key,
  user_id uuid unique,                    -- Nexus account (filled in on first sign-in)
  email text not null unique,             -- always lowercase
  name text,                              -- from Nexus (nickname / username)
  display_name text,                      -- what they want to be called in aARgon3
  role text not null default 'employee' check (role in ('employee', 'manager', 'owner')),
  active boolean not null default true,
  title text, phone text, default_store text, color text, notes text,
  pay_rate numeric(10,2),                 -- dollars an hour; only the owner sees it
  invited_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_seen timestamptz
);

create table if not exists public.schedule (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  store_code text,
  starts_at timestamptz not null,
  ends_at timestamptz not null check (ends_at > starts_at),
  note text,
  created_by text,
  created_at timestamptz not null default now()
);
create index if not exists schedule_time_idx on public.schedule (starts_at);
create index if not exists schedule_user_idx on public.schedule (user_id, starts_at);

create table if not exists public.time_off (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  starts_on date not null,
  ends_on date not null check (ends_on >= starts_on),
  reason text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'denied', 'cancelled')),
  decided_by text, decided_at timestamptz,
  created_at timestamptz not null default now()
);

