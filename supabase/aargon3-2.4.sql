-- abandoned-checkout reminders, store hours and closures.
-- Run once in the aARgon3 & Mexel Backend project's SQL Editor, after aargon3-2.3.sql. Safe to run again.

-- ============================================================ orders: new columns
alter table public.orders add column if not exists region text;                    -- A–E (tax and receipts)
alter table public.orders add column if not exists tax_cents integer not null default 0;
alter table public.orders add column if not exists current_period_end timestamptz; -- next renewal (subscriptions)
alter table public.orders add column if not exists cancel_at timestamptz;          -- cancelling at the end of the period
alter table public.orders add column if not exists paused_until timestamptz;       -- status PAUSED until then
alter table public.orders add column if not exists expires_at timestamptz;         -- gifts: paid-for months run out
alter table public.orders add column if not exists referral_code text;             -- this customer's own code (REF-XXXXXX)
alter table public.orders add column if not exists referred_by text;               -- the code they used
alter table public.orders add column if not exists gift jsonb;                     -- { code, months, to_name, to_email, message, from_name, from_email, claimed_at }
alter table public.orders add column if not exists gift_code text;
alter table public.orders add column if not exists history jsonb not null default '[]'::jsonb;   -- plan changes, pauses, cancels
create unique index if not exists orders_referral_code_idx on public.orders (referral_code) where referral_code is not null;
create unique index if not exists orders_gift_code_idx on public.orders (gift_code) where gift_code is not null;

-- payments: plan-change charges are their own kind
alter table public.payments drop constraint if exists payments_kind_check;
alter table public.payments add constraint payments_kind_check check (kind in ('first', 'renewal', 'change'));

-- ============================================================ referrals: who brought whom, and the month of credit
create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  code text not null,
  referrer_order text not null,
  new_order text not null unique,           -- one reward per new order
  new_email text,
  credit_cents integer not null default 0,  -- credit given to the referrer (0 = over the yearly limit or nothing to credit)
  stripe_txn_id text,
  status text not null default 'credited' check (status in ('credited', 'pending', 'limit')),
  created_at timestamptz not null default now()
);
create index if not exists referrals_code_idx on public.referrals (code, created_at desc);
alter table public.referrals enable row level security;
revoke all on public.referrals from anon, authenticated;

-- ============================================================ customer portal: slow down guessing
create table if not exists public.portal_attempts (
  key text not null,                         -- 'ip:1.2.3.4' or 'order:XXXX'
  at timestamptz not null default now()
);
create index if not exists portal_attempts_idx on public.portal_attempts (key, at);
alter table public.portal_attempts enable row level security;
revoke all on public.portal_attempts from anon, authenticated;

-- ============================================================ abandoned checkouts (only for people who ticked "remind me")
create table if not exists public.abandoned (
  session_id text primary key,
  order_id text,
  email text not null,
  name text,
  label text,                                -- "Business Pro · monthly"
  amount_cents integer,
  link text,                                 -- back to the store with the same plan picked
  emailed_at timestamptz,
  email_error text,
  recovered boolean not null default false,  -- they bought something later
  created_at timestamptz not null default now()
);
alter table public.abandoned enable row level security;
revoke all on public.abandoned from anon, authenticated;

-- ============================================================ store hours and closures
alter table public.stores add column if not exists hours jsonb;     -- {"mon":["09:00","21:00"], ..., "sun":null}  (null day = closed; null hours = not set)
create table if not exists public.closures (
  id bigint generated by default as identity primary key,
  store_code text,                           -- null = the online store
  starts_on date not null,
  ends_on date not null,
  reason text,
  created_by text,
  created_at timestamptz not null default now(),
  check (ends_on >= starts_on)
);
create index if not exists closures_dates_idx on public.closures (ends_on);
alter table public.closures enable row level security;
revoke all on public.closures from anon, authenticated;

